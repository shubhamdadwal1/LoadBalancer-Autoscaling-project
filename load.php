function cpuLoad()
{
    $line = @file('/proc/stat')[0] ?? '';

    $parts = preg_split('/\s+/', trim($line));

    if (count($parts) < 5) {
        return [0, 0];
    }

    $values = array_map('intval', array_slice($parts, 1));

    $total = array_sum($values);

    // user + nice + system + idle + iowait...
    $idle = (int)$parts[4] + (int)($parts[5] ?? 0);

    return [$total, $idle];
}


